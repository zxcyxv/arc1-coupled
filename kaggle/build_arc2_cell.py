"""Writes kaggle/arc2_submission_cell.py: one notebook cell for the ARC Prize 2026 ARC-AGI-2 submission.

    python kaggle/build_arc2_cell.py

The cell is arc/model.py (without the Triton kernels: the PyTorch path) followed by kaggle/arc2_infer.py, behind a CFG
block. Attach the competition data and a Dataset with the EMA checkpoint (checkpoints/run_arc2_b16g10_rope1d/
step_72224.pt), paste the whole file into one cell and run it; it writes /kaggle/working/submission.json.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADER = '''# -*- coding: utf-8 -*-
# TDP-Reasoner (coupled model) for ARC Prize 2026 ARC-AGI-2 -- one Kaggle notebook cell. GENERATED by
# kaggle/build_arc2_cell.py from arc/model.py and kaggle/arc2_infer.py; do not edit here.
# Attach: the competition data and a Dataset holding the EMA checkpoint step_72224.pt (ARC-2 16/10, 1D RoPE, 10k epochs).
# Runs offline (torch + numpy only), on every visible GPU, and writes /kaggle/working/submission.json.
CFG = dict(
    ckpt=None,          # checkpoint path; None: step_72224*.pt (else the first *.pt) under /kaggle/input
    challenges=None,    # None: arc-agi_test_challenges.json under /kaggle/input
    versions=8,         # vote over the original + 7 augmented versions
    segments=16,        # recursion segments per lane (the training loops)
    lanes=32,           # lanes per micro-batch per GPU
    seed=42,
    out='/kaggle/working/submission.json',
    max_tasks=None,     # debugging: run only the first N tasks (the file still lists every task)
    solutions=None,     # optional solutions json: prints the task-weighted pass@2
)
'''


def main():
    model = (ROOT / 'arc' / 'model.py').read_text()
    start = model.index('try:\n    from .rope_kernel')
    end = model.index('sums_fwd = None\n', start) + len('sums_fwd = None\n')
    model = model[:start] + 'qk_rope = bands_sums_bwd = bands_sums_fwd = sums_bwd = sums_fwd = None   # PyTorch path\n' + model[end:]
    infer = (ROOT / 'kaggle' / 'arc2_infer.py').read_text()
    out = ROOT / 'kaggle' / 'arc2_submission_cell.py'
    out.write_text(HEADER + '\n# ---------------------------------------------------------------------------------------------------- model'
                   '\n# arc/model.py\n' + model + '\n' + infer)
    print(f'wrote {out} ({len(out.read_text().splitlines())} lines)')


if __name__ == '__main__':
    main()
